"""What a run wrote to GitHub, read back and compared with what it sent (ADR 0024).

A Claude Code cloud session's PR came back with a footer the run never sent:
a rule, then a line linking the session. The run's attribution settings did
not stop it. So a run reads each body back, takes off exactly that footer by
writing back the body it sent, and fails on any other difference, which it
never tries to repair.
"""

from __future__ import annotations

import enum
import re
from typing import Callable, Protocol

from trimtab.capture.prblock import run_references

# The platform's footer, at the very end of a body: the session link, after a rule.
FOOTER_LINK = re.compile(r"\n*_Generated by \[Claude Code\]\(https://claude\.ai/code/session_[0-9A-Za-z]+\)_\Z")
FOOTER_RULE = re.compile(r"\n*---\Z")
# How long a run waits before each read: the footer may be added after the write returns.
SETTLE_SECONDS = 10.0


class WrittenBodyError(Exception):
    """A body read back is not the one sent, or still holds a run reference. Never quotes the body.

    `targets` are the (kind, number) pairs it is about, each named in the message.
    """

    def __init__(self, message: str, targets: list[tuple[str, int]] | None = None):
        super().__init__(message)
        self.targets = targets or []


class Readback(enum.Enum):
    SAME = "the body is the one sent"
    FOOTER = "the platform's session footer was after the body sent"
    DIFFERS = "the body differs from the one sent, other than by the platform's footer"


class Bodies(Protocol):
    """Where bodies are read and written: `kind` is pull, issue or comment."""

    def read(self, kind: str, number: int) -> str: ...

    def write(self, kind: str, number: int, body: str) -> None: ...


def _plain(text: str) -> str:
    """GitHub may store CRLF line ends and drop trailing space; neither is a change."""
    return text.replace("\r\n", "\n").rstrip()


def compare(sent: str, found: str) -> Readback:
    """SAME; FOOTER when `found` is `sent` plus the platform's session link, with or without its rule; else DIFFERS.

    The rule is tried both ways, so a body that itself ends with a `---` rule keeps it.
    """
    sent, found = _plain(sent), _plain(found)
    if found == sent:
        return Readback.SAME
    link = FOOTER_LINK.search(found)
    if link:
        head = _plain(found[:link.start()])
        if sent in (head, _plain(FOOTER_RULE.sub("", head))):
            return Readback.FOOTER
    return Readback.DIFFERS


Target = tuple[str, int, str]  # (kind, number, body sent)


def verify_bodies(bodies: Bodies, targets: list[Target], *,
                  settle_seconds: float, sleep: Callable[[float], None]) -> list[Readback]:
    """Read back each target after one shared wait; take the platform footer off every one that carries it, wait
    once more, and require them identical. Any other change, or a run reference, fails, but only after every
    target has been checked and every footer taken off: one WrittenBodyError names each target that failed.
    The caller supplies the wait (`sleep`): waiting is the outer layer's."""

    def wait() -> None:
        if settle_seconds > 0:
            sleep(settle_seconds)

    failures: list[tuple[tuple[str, int], str]] = []
    # A body that holds a reference fails before any wait, and is never written back.
    for kind, number, sent in targets:
        references = run_references(sent)
        if references:
            failures.append(((kind, number), f"the body holds a run reference "
                                             f"({', '.join(p.where for p in references)})"))
    held = {target for target, _ in failures}
    checked = [t for t in targets if (t[0], t[1]) not in held]
    outcomes: dict[tuple[str, int], Readback] = {}
    if checked:
        wait()
    for kind, number, sent in checked:
        outcome = compare(sent, bodies.read(kind, number))
        if outcome is Readback.DIFFERS:
            failures.append(((kind, number), outcome.value))
        else:
            outcomes[(kind, number)] = outcome
    # Every footer found is taken off, whatever else in the batch failed.
    footed = [t for t in checked if outcomes.get((t[0], t[1])) is Readback.FOOTER]
    for kind, number, sent in footed:
        bodies.write(kind, number, sent)
    if footed:
        wait()
    for kind, number, sent in footed:
        if compare(sent, bodies.read(kind, number)) is not Readback.SAME:
            failures.append(((kind, number), "the platform's footer came back after the body sent was written again"))
    if failures:
        raise WrittenBodyError("; ".join(f"{kind} {number}: {why}" for (kind, number), why in failures),
                               [target for target, _ in failures])
    return [outcomes[(kind, number)] for kind, number, _ in targets]


def verify_body(bodies: Bodies, kind: str, number: int, sent: str, *,
                settle_seconds: float, sleep: Callable[[float], None]) -> Readback:
    """`verify_bodies` for one body."""
    return verify_bodies(bodies, [(kind, number, sent)], settle_seconds=settle_seconds, sleep=sleep)[0]
