"""What a run wrote to GitHub, read back and compared with what it sent (ADR 0024).

A Claude Code cloud session's PR came back with a footer the run never sent:
a rule, then a line linking the session. The run's attribution settings did
not stop it. So a run reads each body back, takes off exactly that footer by
writing back the body it sent, and fails on any other difference, which it
never tries to repair.

The first trial showed the platform adding a second form on the write-back: the
same line, linking no session. That one names nothing, and writing again only
brings it back, so it is accepted and left where it is.

A later run (2026-10-17) showed a third form on create: the footer not after the
body but in place of its last line, the run's own attribution line. Either footer
in that place (IN_PLACE) has deleted text the run sent, so it is always written
back, session link or not, and the body must come back as sent or with only the
generic footer after it.
"""

from __future__ import annotations

import enum
import re
from typing import Callable, Protocol

from trimtab.capture.prblock import run_references

# The platform's footer, at the very end of a body: the session link, after a rule.
FOOTER_LINK = re.compile(r"\n*_Generated by \[Claude Code\]\(https://claude\.ai/code/session_[0-9A-Za-z]+\)_\Z")
# The platform's footer on an edit: the same line, linking no session.
FOOTER_GENERIC = re.compile(r"\n*_Generated by \[Claude Code\]\(https://claude\.ai/code\)_\Z")
FOOTER_RULE = re.compile(r"\n*---\Z")
# The run's own attribution line, which the platform has been seen to replace with its footer.
ATTRIBUTION = re.compile(r"(?:\A|\n+)🤖 Generated with \[Claude Code\]\(https://claude\.com/claude-code\)\Z")
# How long a run waits before each read: the footer may be added after the write returns.
SETTLE_SECONDS = 10.0


class WrittenBodyError(Exception):
    """A body read back is not the one sent, or still holds a run reference. Never quotes the body.

    `targets` are the (kind, number) pairs it is about, each named in the message.
    """

    def __init__(self, message: str, targets: list[tuple[str, int]] | None = None):
        super().__init__(message)
        self.targets = targets or []


class Readback(enum.Enum):
    SAME = "the body is the one sent"
    FOOTER = "the platform's session footer was after the body sent"
    IN_PLACE = "the platform's session footer stood in place of the body's attribution line, now restored"
    IN_PLACE_GENERIC = ("the platform's generic footer, linking no session, stood in place of the body's attribution "
                        "line, now restored")
    GENERIC = "the platform's generic footer, linking no session, is after the body sent"
    REPLACED = "the platform's session footer was taken off, and the platform put its generic footer in its place"
    IN_PLACE_REPLACED = ("the platform's session footer stood in place of the body's attribution line; the line is "
                         "restored, and the platform's generic footer follows it")
    IN_PLACE_GENERIC_KEPT = ("the platform's generic footer, linking no session, stood in place of the body's "
                             "attribution line; the line is restored, and that footer follows it")
    DIFFERS = "the body differs from the one sent, other than by the platform's footer"


class Bodies(Protocol):
    """Where bodies are read and written: `kind` is pull, issue or comment."""

    def read(self, kind: str, number: int) -> str: ...

    def write(self, kind: str, number: int, body: str) -> None: ...


def _plain(text: str) -> str:
    """GitHub may store CRLF line ends and drop trailing space; neither is a change."""
    return text.replace("\r\n", "\n").rstrip()


def compare(sent: str, found: str) -> Readback:
    """SAME; FOOTER when `found` is `sent` plus the platform's session link, GENERIC when it is `sent` plus the
    platform's line linking no session, each with or without its rule; IN_PLACE (session link) or IN_PLACE_GENERIC
    when that footer stands where `sent`'s last line, the run's attribution line, was; else DIFFERS.

    The rule is tried both ways, so a body that itself ends with a `---` rule keeps it. Never REPLACED: that is
    what a write-back came to, which only `verify_bodies` knows.
    """
    sent, found = _plain(sent), _plain(found)
    if found == sent:
        return Readback.SAME
    for footer, after, in_place in ((FOOTER_LINK, Readback.FOOTER, Readback.IN_PLACE),
                                    (FOOTER_GENERIC, Readback.GENERIC, Readback.IN_PLACE_GENERIC)):
        match = footer.search(found)
        if match:
            head = _plain(found[:match.start()])
            heads = {head, _plain(FOOTER_RULE.sub("", head))}
            if sent in heads:
                return after
            stripped = _plain(ATTRIBUTION.sub("", sent))
            if stripped != sent and stripped in heads:
                return in_place
    return Readback.DIFFERS


Target = tuple[str, int, str]  # (kind, number, body sent)

# What a first read is written back for, and what it becomes when the generic footer follows the body sent after.
WRITTEN_BACK = {Readback.FOOTER: Readback.REPLACED, Readback.IN_PLACE: Readback.IN_PLACE_REPLACED,
                Readback.IN_PLACE_GENERIC: Readback.IN_PLACE_GENERIC_KEPT}


def verify_bodies(bodies: Bodies, targets: list[Target], *,
                  settle_seconds: float, sleep: Callable[[float], None]) -> list[Readback]:
    """Read back each target after one shared wait; write back the body sent to every one that carries the
    platform's session footer or has a footer in place of its attribution line, wait once more, and require them
    identical, or carrying only the generic footer after the body sent (REPLACED). A generic footer
    found on the first read is left alone (GENERIC): it names nothing, and a write would only bring it back. Any
    other change, or a run reference, fails, but only after every target has been checked and every session footer
    taken off: one WrittenBodyError names each target that failed. A read or write that fails (GitHub) does not stop
    the others either. If that is all that failed, the first such error is raised as it came; if a body also failed,
    the WrittenBodyError names both, each by its target. The caller supplies the wait (`sleep`): waiting is the
    outer layer's."""

    def wait() -> None:
        if settle_seconds > 0:
            sleep(settle_seconds)

    failures: list[tuple[tuple[str, int], str]] = []
    # A body that holds a reference fails before any wait, and is never written back.
    for kind, number, sent in targets:
        references = run_references(sent)
        if references:
            failures.append(((kind, number), f"the body holds a run reference "
                                             f"({', '.join(p.where for p in references)})"))
    # A read or write that fails for one body is kept and re-raised at the end, so every footer the batch can
    # reach is still taken off first.
    errors: list[tuple[tuple[str, int], Exception]] = []

    def read(kind: str, number: int) -> str | None:
        try:
            return bodies.read(kind, number)
        except Exception as err:  # raised below, after the rest of the batch
            errors.append(((kind, number), err))
            return None

    def write(kind: str, number: int, sent: str) -> bool:
        try:
            bodies.write(kind, number, sent)
            return True
        except Exception as err:  # raised below, after the rest of the batch
            errors.append(((kind, number), err))
            return False

    held = {target for target, _ in failures}
    checked = [t for t in targets if (t[0], t[1]) not in held]
    outcomes: dict[tuple[str, int], Readback] = {}
    if checked:
        wait()
    for kind, number, sent in checked:
        body = read(kind, number)
        if body is None:
            continue
        outcome = compare(sent, body)
        if outcome is Readback.DIFFERS:
            failures.append(((kind, number), outcome.value))
        else:
            outcomes[(kind, number)] = outcome
    # Every session footer and every footer in place of the attribution line is written over, whatever else in the
    # batch failed; a generic footer after the body sent is left, since a write only brings it back.
    footed = [t for t in checked if outcomes.get((t[0], t[1])) in WRITTEN_BACK]
    written = [t for t in footed if write(*t)]
    if written:
        wait()
    for kind, number, sent in written:
        body = read(kind, number)
        if body is None:
            continue
        again = compare(sent, body)
        if again is Readback.GENERIC:
            outcomes[(kind, number)] = WRITTEN_BACK[outcomes[(kind, number)]]
        elif again is Readback.FOOTER:
            failures.append(((kind, number), "the platform's footer came back after the body sent was written again"))
        elif again in (Readback.IN_PLACE, Readback.IN_PLACE_GENERIC):
            failures.append(((kind, number), "the platform's footer replaced the attribution line again after the "
                                             "body sent was written again"))
        elif again is not Readback.SAME:
            failures.append(((kind, number), "the body differs from the one sent after it was written again"))
    if errors and not failures:
        raise errors[0][1]  # GitHub's error, as raised: the caller decides what an unread body means
    if failures:
        # Both kinds name their bodies: a changed body is never hidden behind a GitHub error.
        why = [f"{kind} {number}: {reason}" for (kind, number), reason in failures]
        why += [f"{kind} {number}: not read back ({err})" for (kind, number), err in errors]
        raise WrittenBodyError("; ".join(why), [t for t, _ in failures] + [t for t, _ in errors]) from (
            errors[0][1] if errors else None)
    return [outcomes[(kind, number)] for kind, number, _ in targets]


def verify_body(bodies: Bodies, kind: str, number: int, sent: str, *,
                settle_seconds: float, sleep: Callable[[float], None]) -> Readback:
    """`verify_bodies` for one body."""
    return verify_bodies(bodies, [(kind, number, sent)], settle_seconds=settle_seconds, sleep=sleep)[0]
