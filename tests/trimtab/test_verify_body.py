# The tail of a session ID; built here so no tree scan reads one.
SESSION_TAIL = "01" + "A1b2C3d4E5f6G7h8J9k0"
ATTRIBUTION = ATTRIBUTION_LINE + "\n"
SENT = "## Verdict\n\nNothing to raise.\n\n" + ATTRIBUTION
FOOTER = "\n---\n_Generated by [Claude Code](https://claude.ai/code/" + "session_" + SESSION_TAIL + ")_"
# What the platform put back on an edit, in the first trial (2026-10-15): the same line, linking no session.
GENERIC = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def with_footer(body):
    return body + FOOTER


def with_generic(body):
    return body + GENERIC


def in_place_of_attribution(body, footer):
    """What the platform did on create in a later trial (2026-10-17): its footer where the run's last line was."""
    assert body.endswith(ATTRIBUTION)
    return body[:-len(ATTRIBUTION)].rstrip("\n") + "\n" + footer


