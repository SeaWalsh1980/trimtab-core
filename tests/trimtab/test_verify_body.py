"""A run reads back what it wrote to GitHub, and takes the platform's session footer off (ADR 0024).

A cloud session's PR came back with a footer after the body the run sent: a
rule and a line linking the session. The run's settings did not stop it, so
the run reads each body back, removes exactly that footer, and fails on
anything else it did not send.
"""

import contextlib
import io
import json
import os
import subprocess
import tempfile
import unittest
from pathlib import Path

from gh_fake import FakeGh, method_of, path_of
from instance_fixture import env_for
from trimtab.capture.sources import GhBodies, GhIssues, SourceError
from trimtab.capture.written import Readback, WrittenBodyError, compare, verify_body
from trimtab.cli import _opening_stopped
from trimtab.propose import OpeningStopped

REPO = "owner/repo"
PR = 931
ISSUE = 9
COMMENT = 4242
ISSUE_URL = f"https://github.com/{REPO}/issues/{ISSUE}"
# The tail of a session ID; built here so no tree scan reads one.
SESSION_TAIL = "01" + "A1b2C3d4E5f6G7h8J9k0"
SENT = "## Verdict\n\nNothing to raise.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n"
FOOTER = "\n---\n_Generated by [Claude Code](https://claude.ai/code/" + "session_" + SESSION_TAIL + ")_"


def with_footer(body):
    return body + FOOTER


class Compare(unittest.TestCase):
    def test_the_body_sent_back_unchanged_is_the_same(self):
        self.assertIs(compare(SENT, SENT), Readback.SAME)

    def test_line_endings_and_trailing_space_do_not_count_as_a_change(self):
        self.assertIs(compare(SENT, SENT.replace("\n", "\r\n").rstrip()), Readback.SAME)

    def test_the_platform_footer_after_the_body_is_recognised(self):
        self.assertIs(compare(SENT, with_footer(SENT)), Readback.FOOTER)

    def test_a_body_ending_with_its_own_rule_keeps_it_when_the_footer_follows(self):
        sent = SENT + "\n---\n"

        self.assertIs(compare(sent, with_footer(sent)), Readback.FOOTER)

    def test_the_session_link_without_its_rule_is_recognised(self):
        self.assertIs(compare(SENT, SENT + FOOTER.replace("\n---", "")), Readback.FOOTER)

    def test_text_after_the_footer_is_a_difference(self):
        self.assertIs(compare(SENT, with_footer(SENT) + "\nmore"), Readback.DIFFERS)

    def test_other_text_after_the_body_is_a_difference(self):
        self.assertIs(compare(SENT, SENT + "\n---\n_Generated by someone else_"), Readback.DIFFERS)

    def test_the_footer_inside_the_body_is_a_difference(self):
        self.assertIs(compare(SENT, "intro" + FOOTER + "\n" + SENT), Readback.DIFFERS)

    def test_a_changed_body_is_a_difference(self):
        self.assertIs(compare(SENT, SENT.replace("Nothing", "Something")), Readback.DIFFERS)


class InMemoryBodies:
    """One repository's body for one (kind, number); any other target is a KeyError, so a wrong read shows.

    `then` is what a read returns after a write; `arrives` is what the body becomes once the run has waited.
    """

    def __init__(self, target, found, then=None, arrives=None):
        self.target = target
        self.found = found
        self.then = then
        self.arrives = arrives
        self.writes = []
        self.waits = []

    def read(self, kind, number):
        if (kind, number) != self.target:
            raise KeyError((kind, number))
        return self.found

    def write(self, kind, number, body):
        if (kind, number) != self.target:
            raise KeyError((kind, number))
        self.writes.append(body)
        self.found = self.then if self.then is not None else body

    def sleep(self, seconds):
        self.waits.append(seconds)
        if self.arrives is not None and not self.writes:
            self.found, self.arrives = self.arrives, None


def verify(bodies, sent, settle_seconds=0.0):
    return verify_body(bodies, *bodies.target, sent, settle_seconds=settle_seconds, sleep=bodies.sleep)


class VerifyBody(unittest.TestCase):
    def test_a_body_that_came_back_unchanged_is_left_alone(self):
        bodies = InMemoryBodies(("pull", PR), SENT)

        outcome = verify(bodies, SENT)

        self.assertEqual((outcome, bodies.writes), (Readback.SAME, []))

    def test_the_footer_is_taken_off_by_writing_back_the_body_sent(self):
        bodies = InMemoryBodies(("pull", PR), with_footer(SENT))

        outcome = verify(bodies, SENT)

        self.assertEqual((outcome, bodies.writes, bodies.found), (Readback.FOOTER, [SENT], SENT))

    def test_a_footer_added_while_the_run_waits_is_still_taken_off(self):
        bodies = InMemoryBodies(("pull", PR), SENT, arrives=with_footer(SENT))

        outcome = verify(bodies, SENT, settle_seconds=10)

        self.assertEqual((outcome, bodies.writes, bodies.found), (Readback.FOOTER, [SENT], SENT))

    def test_the_run_waits_before_each_read(self):
        bodies = InMemoryBodies(("pull", PR), with_footer(SENT))

        verify(bodies, SENT, settle_seconds=10)

        self.assertEqual(bodies.waits, [10, 10])

    def test_a_footer_that_comes_back_after_the_write_fails(self):
        bodies = InMemoryBodies(("pull", PR), with_footer(SENT), then=with_footer(SENT))

        with self.assertRaises(WrittenBodyError):
            verify(bodies, SENT)

    def test_a_body_that_differs_otherwise_is_never_written(self):
        bodies = InMemoryBodies(("issue", ISSUE), SENT + "\nappended")

        with self.assertRaises(WrittenBodyError):
            verify(bodies, SENT)

        self.assertEqual(bodies.writes, [])

    def test_the_error_never_quotes_the_session_id(self):
        bodies = InMemoryBodies(("pull", PR), with_footer(SENT) + "\nmore")

        with self.assertRaises(WrittenBodyError) as caught:
            verify(bodies, SENT)

        self.assertNotIn(SESSION_TAIL, str(caught.exception))

    def test_a_run_reference_in_the_body_sent_fails_even_when_it_came_back_unchanged(self):
        sent = SENT + "see " + "session_" + SESSION_TAIL + "\n"
        bodies = InMemoryBodies(("comment", COMMENT), sent)

        with self.assertRaises(WrittenBodyError):
            verify(bodies, sent)


class GhBodiesPaths(unittest.TestCase):
    def test_each_kind_reads_its_repository_path(self):
        cases = {"pull": f"repos/{REPO}/pulls/{PR}", "issue": f"repos/{REPO}/issues/{ISSUE}",
                 "comment": f"repos/{REPO}/issues/comments/{COMMENT}"}
        for kind, path in cases.items():
            with self.subTest(kind=kind):
                gh = FakeGh(default=json.dumps({"body": SENT}))
                number = {"pull": PR, "issue": ISSUE, "comment": COMMENT}[kind]

                body = GhBodies(REPO, run=gh).read(kind, number)

                self.assertEqual((method_of(gh.argvs()[0]), path_of(gh.argvs()[0]), body), ("GET", path, SENT))

    def test_a_null_body_reads_as_empty(self):
        gh = FakeGh(default=json.dumps({"body": None}))

        self.assertEqual(GhBodies(REPO, run=gh).read("pull", PR), "")

    def test_writing_patches_the_body_on_stdin(self):
        gh = FakeGh(default="{}")

        GhBodies(REPO, run=gh).write("comment", COMMENT, SENT)

        (argv, stdin), = gh.calls
        self.assertEqual((method_of(argv), path_of(argv), json.loads(stdin)),
                         ("PATCH", f"repos/{REPO}/issues/comments/{COMMENT}", {"body": SENT}))

    def test_an_unknown_kind_is_refused_before_gh_runs(self):
        gh = FakeGh(default="{}")

        with self.assertRaises(SourceError):
            GhBodies(REPO, run=gh).read("release", 1)

        self.assertEqual(gh.calls, [])


class CreatedIssues(unittest.TestCase):
    """`propose --apply` files issues from Python, past the PR-body hook: each is read back too."""

    def created(self, *bodies_read):
        return FakeGh(answers={
            ("POST", f"repos/{REPO}/issues"): json.dumps({"html_url": ISSUE_URL, "number": ISSUE}),
            ("GET", f"repos/{REPO}/issues/{ISSUE}"): [json.dumps({"body": b}) for b in bodies_read],
        }, default="{}")

    def test_an_issue_that_came_back_unchanged_is_not_edited(self):
        gh = self.created(SENT)

        url = GhIssues(REPO, run=gh, settle_seconds=0).create("title", SENT, ["harness-feedback"])

        self.assertEqual((url, [method_of(a) for a in gh.argvs()]), (ISSUE_URL, ["POST", "GET"]))

    def test_an_issue_that_came_back_with_the_footer_has_it_taken_off(self):
        gh = self.created(with_footer(SENT), SENT)

        GhIssues(REPO, run=gh, settle_seconds=0).create("title", SENT, ["harness-feedback"])

        patch = [(path_of(a), json.loads(s)) for a, s in gh.calls if method_of(a) == "PATCH"]
        self.assertEqual(patch, [(f"repos/{REPO}/issues/{ISSUE}", {"body": SENT})])

    def test_an_issue_that_came_back_otherwise_changed_fails_naming_it(self):
        gh = self.created(SENT + "\nappended")

        with self.assertRaises(WrittenBodyError) as caught:
            GhIssues(REPO, run=gh, settle_seconds=0).create("title", SENT, ["harness-feedback"])

        self.assertIn(ISSUE_URL, str(caught.exception))


class ProposeStoppedReport(unittest.TestCase):
    """What `propose --apply` reports when opening stops part-way, and its exit code."""

    def report(self, cause):
        stopped = OpeningStopped(["https://github.com/o/t/issues/1"], "ENG-2", ["SEC-1"], cause)
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = _opening_stopped(stopped)
        return code, out.getvalue(), err.getvalue()

    def test_a_body_that_came_back_changed_exits_1_listing_what_was_opened_and_not(self):
        code, out, err = self.report(WrittenBodyError("differs"))

        self.assertEqual((code, "issues/1" in out, "SEC-1" in err, "Stop and report" in err), (1, True, True, True))

    def test_a_github_failure_exits_2_and_says_a_re_run_files_nothing_twice(self):
        code, out, err = self.report(SourceError("HTTP 500"))

        self.assertEqual((code, "issues/1" in out, "Re-run" in err), (2, True, True))

    def test_any_other_cause_is_raised_not_reported(self):
        with self.assertRaises(RuntimeError):
            self.report(RuntimeError("a fault"))


FAKE_GH = """#!/bin/sh
# Answers every gh call with the same JSON: enough for one read, and a write that changes nothing.
cat "$FAKE_GH_ANSWER"
"""


class VerifyBodyCli(unittest.TestCase):
    """`trimtab verify-body`: exit 0 when the body is the one sent, 1 when it is not, 2 when it cannot tell."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.dir = Path(self._tmp.name)
        bin_dir = self.dir / "bin"
        bin_dir.mkdir()
        gh = bin_dir / "gh"
        gh.write_text(FAKE_GH, encoding="utf-8")
        gh.chmod(0o755)
        self.answer = self.dir / "answer.json"
        self.body = self.dir / "body.md"
        self.body.write_text(SENT, encoding="utf-8")
        self.env = env_for(None)
        self.env.update(PATH=f"{bin_dir}{os.pathsep}{self.env.get('PATH', '')}", FAKE_GH_ANSWER=str(self.answer))

    def tearDown(self):
        self._tmp.cleanup()

    def verify(self, *args):
        trimtab = Path(__file__).resolve().parents[2] / "bin" / "trimtab"
        return subprocess.run([str(trimtab), "verify-body", "--repo", REPO, "--settle", "0", *args], capture_output=True, text=True,
                              cwd=self.dir, env=self.env)

    def test_a_body_that_came_back_unchanged_exits_0(self):
        self.answer.write_text(json.dumps({"body": SENT}), encoding="utf-8")

        done = self.verify("--pull", str(PR), "--body-file", str(self.body))

        self.assertEqual(done.returncode, 0, done.stderr)

    def test_a_footer_that_will_not_come_off_exits_1_without_quoting_it(self):
        self.answer.write_text(json.dumps({"body": with_footer(SENT)}), encoding="utf-8")

        done = self.verify("--pull", str(PR), "--body-file", str(self.body))

        self.assertEqual(done.returncode, 1)
        self.assertNotIn(SESSION_TAIL, done.stdout + done.stderr)

    def test_a_body_that_differs_exits_1(self):
        self.answer.write_text(json.dumps({"body": SENT + "\nappended"}), encoding="utf-8")

        done = self.verify("--issue", str(ISSUE), "--body-file", str(self.body))

        self.assertEqual(done.returncode, 1)

    def test_a_body_given_inline_is_compared_too(self):
        self.answer.write_text(json.dumps({"body": "https://github.com/owner/repo/pull/5"}), encoding="utf-8")

        done = self.verify("--comment", str(COMMENT), "--body", "https://github.com/owner/repo/pull/5")

        self.assertEqual(done.returncode, 0, done.stderr)

    def test_a_failing_gh_exits_2(self):
        self.answer.write_text("not json", encoding="utf-8")

        done = self.verify("--pull", str(PR), "--body-file", str(self.body))

        self.assertEqual(done.returncode, 2)

    def test_an_unreadable_body_file_exits_2(self):
        done = self.verify("--pull", str(PR), "--body-file", str(self.dir / "missing.md"))

        self.assertEqual(done.returncode, 2)

    def test_no_target_exits_2(self):
        done = self.verify("--body-file", str(self.body))

        self.assertEqual(done.returncode, 2)


if __name__ == "__main__":
    unittest.main()
